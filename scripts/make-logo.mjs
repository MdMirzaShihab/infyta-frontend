// Builds the Infyta logo with the wordmark and tagline as outlines, so it needs no font.
// Writes src/components/logo-paths.js and the logo SVG files in public/images/.
// Run: node scripts/make-logo.mjs (then node scripts/make-brand-images.mjs)
// The geometry is the redraw measured from the old 200x119 raster; this script is now its source.
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadFont, glyphAt, lineAt } from './lib/text-path.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const f = (n) => Number(n.toFixed(2));
const pt = (p) => `${f(p[0])} ${f(p[1])}`;

// Polygon with per-corner radius, corners drawn as quadratic curves.
function rounded(points, radii) {
  const n = points.length;
  let d = '';
  for (let i = 0; i < n; i++) {
    const p0 = points[(i - 1 + n) % n], p1 = points[i], p2 = points[(i + 1) % n];
    const r = Array.isArray(radii) ? radii[i] : radii;
    const v1 = [p0[0] - p1[0], p0[1] - p1[1]], v2 = [p2[0] - p1[0], p2[1] - p1[1]];
    const l1 = Math.hypot(...v1), l2 = Math.hypot(...v2);
    const ang = Math.acos((v1[0] * v2[0] + v1[1] * v2[1]) / (l1 * l2));
    const dist = Math.min(r / Math.tan(ang / 2), l1 / 2, l2 / 2);
    const a = [p1[0] + (v1[0] / l1) * dist, p1[1] + (v1[1] / l1) * dist];
    const b = [p1[0] + (v2[0] / l2) * dist, p1[1] + (v2[1] / l2) * dist];
    d += `${i ? 'L' : 'M'}${pt(a)}Q${pt(p1)} ${pt(b)}`;
  }
  return d + 'Z';
}

const K = 0.6; // isometric edge slope measured from the raster
// A tile: vertical sides, top/bottom edges rising to the right.
const tile = (x0, x1, yTopLeft, h, r) =>
  rounded([[x0, yTopLeft], [x1, yTopLeft - K * (x1 - x0)], [x1, yTopLeft - K * (x1 - x0) + h], [x0, yTopLeft + h]], r);

const shapes = {
  wall: rounded([[0, 49.4], [55, 81.5], [55, 120.3], [0, 88.2]], [1.2, 3, 7, 1.2]),
  floor: rounded([[5.5, 47.5], [62.5, 13.3], [62.5, 52.6], [38, 67.3]], [1.6, 0, 0, 1.6]),
  t1: tile(25.5, 46.8, 24.9, 19.8, 3),
  t2: tile(51.5, 70.8, 9.3, 17.5, 3),
  t3: tile(51.5, 75.8, 31.2, 23.2, 3.4),
};

// Wordmark: Montserrat ExtraBold, dotless i (the dot is the ring), each glyph's left edge placed.
const montserrat = loadFont('@fontsource/montserrat/files/montserrat-latin-800-normal.woff');
const LEFT_EDGES = [63, 79, 108, 127, 156, 178];
const glyphs = [...'ınfyta'].map((ch, i) => ({ ch, ...glyphAt(montserrat, ch, LEFT_EDGES[i], 98, 42.5) }));

// Tagline: Barlow Semi Condensed Medium, fitted to 136 wide.
const barlow = loadFont('@fontsource/barlow-semi-condensed/files/barlow-semi-condensed-latin-500-normal.woff');
const tagline = lineAt(barlow, 'Engineering Tomorrow’s Tech Today', 63, 117.2, 9.8, 136);

for (const g of glyphs) {
  const b = g.box;
  console.log(`${g.ch}  x ${b.x1.toFixed(1)} to ${b.x2.toFixed(1)}  y ${b.y1.toFixed(1)} to ${b.y2.toFixed(1)}`);
}
console.log(`tagline width ${tagline.width.toFixed(1)}`);

const iTop = glyphs[0].box.y1;
const aRight = glyphs[5].box.x2;
const problems = [];
if (!(iTop >= 74 && iTop <= 77)) problems.push(`top of the dotless i is y = ${iTop.toFixed(2)}, expected 74 to 77`);
if (!(aRight >= 199.5 && aRight <= 202)) problems.push(`right edge of the a is x = ${aRight.toFixed(2)}, expected 199.5 to 202`);
if (problems.length) {
  console.error(`make-logo: the wordmark does not sit where the redraw puts it (wrong font file?):\n  ${problems.join('\n  ')}`);
  process.exit(1);
}

const logoPaths = {
  wall: shapes.wall,
  floor: shapes.floor,
  tiles: [shapes.t1, shapes.t2, shapes.t3],
  word: glyphs.map((g) => ({ d: g.d, accent: g.ch === 'y' })),
  tagline: tagline.d,
};

writeFileSync(
  resolve(root, 'src/components/logo-paths.js'),
  `// Generated by scripts/make-logo.mjs. Do not edit by hand.\nexport const logoPaths = ${JSON.stringify(logoPaths, null, 2)};\n`,
);

const CYAN = '#14b9da';
// word: '#ffffff' (reversed, for navy grounds) or '#1f2c62' (ink, for paper grounds).
// Without the tagline the file is 121 high, not the header's 112, so the whole wall (down to y 116.2) shows.
function logoSvg({ word, withTagline, id }) {
  const tiles = logoPaths.tiles.map((d) => `<path d="${d}"/>`).join('');
  const letters = logoPaths.word.map((g) => `<path d="${g.d}"${g.accent ? ` fill="${CYAN}"` : ''}/>`).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="-2 -4 205 ${withTagline ? 125 : 121}" role="img" aria-label="Infyta">
  <defs>
    <linearGradient id="${id}-w" gradientUnits="userSpaceOnUse" x1="0" y1="50" x2="48" y2="108"><stop offset="0" stop-color="#14b9da"/><stop offset="1" stop-color="#212b60"/></linearGradient>
    <linearGradient id="${id}-t" gradientUnits="userSpaceOnUse" x1="70" y1="2" x2="45" y2="45"><stop offset="0" stop-color="#3cc4c4"/><stop offset="1" stop-color="#212b60"/></linearGradient>
    <mask id="${id}-m" maskUnits="userSpaceOnUse" x="-2" y="-4" width="205" height="130">
      <rect x="-2" y="-4" width="205" height="130" fill="#fff"/>
      <g fill="#000" transform="translate(2 4.2)">${tiles}</g>
    </mask>
  </defs>
  <path d="${logoPaths.wall}" fill="url(#${id}-w)"/>
  <path d="${logoPaths.floor}" fill="${word}" mask="url(#${id}-m)"/>
  <g fill="url(#${id}-t)">${tiles}</g>
  <circle cx="67.4" cy="69.5" r="4.7" fill="${word}"/><circle cx="66.2" cy="70.2" r="3.8" fill="${CYAN}"/>
  <g fill="${word}">${letters}</g>${withTagline ? `
  <path d="${logoPaths.tagline}" fill="${word}" opacity=".88"/>` : ''}
</svg>
`;
}

const files = {
  'infyta-logo.svg': { word: '#1f2c62', withTagline: true, id: 'k' },
  'infyta-logo-notagline.svg': { word: '#1f2c62', withTagline: false, id: 'k' },
  'infyta-logo-reversed.svg': { word: '#ffffff', withTagline: true, id: 'r' },
  'infyta-logo-reversed-notagline.svg': { word: '#ffffff', withTagline: false, id: 'r' },
};
for (const [file, opts] of Object.entries(files)) writeFileSync(resolve(root, 'public/images', file), logoSvg(opts));

console.log('logo ok');
